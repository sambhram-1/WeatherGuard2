export function playSosCountdownTick(secondNumber: number, enabled = true) {
  if (!enabled) return;
  try {
    const ctx = getAudioContext();
    if (!ctx) return;
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    osc.type = 'square';
    // Pitches: 3s=520Hz, 2s=680Hz, 1s=880Hz
    const freq = 500 + (4 - secondNumber) * 150;
    osc.frequency.setValueAtTime(freq, ctx.currentTime);
    gain.gain.setValueAtTime(0.2, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.005, ctx.currentTime + 0.12);
    osc.connect(gain);
    gain.connect(ctx.destination);
    osc.start();
    osc.stop(ctx.currentTime + 0.12);
  } catch {
    // Ignore audio errors
  }
}

let sirenInterval: any = null;

export function playSosEmergencySiren(start = true, enabled = true) {
  if (!start || !enabled) {
    if (sirenInterval) {
      clearInterval(sirenInterval);
      sirenInterval = null;
    }
    return;
  }

  try {
    const ctx = getAudioContext();
    if (!ctx) return;

    if (sirenInterval) clearInterval(sirenInterval);

    let high = true;
    const playBurst = () => {
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();
      osc.type = 'sawtooth';
      osc.frequency.setValueAtTime(high ? 900 : 650, ctx.currentTime);
      gain.gain.setValueAtTime(0.22, ctx.currentTime);
      gain.gain.exponentialRampToValueAtTime(0.01, ctx.currentTime + 0.28);
      osc.connect(gain);
      gain.connect(ctx.destination);
      osc.start();
      osc.stop(ctx.currentTime + 0.28);
      high = !high;
    };

    playBurst();
    sirenInterval = setInterval(playBurst, 320);
  } catch {
    // Ignore audio errors
  }
}
